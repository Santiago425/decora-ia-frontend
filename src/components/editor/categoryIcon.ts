import {
  Archive,
  Armchair,
  Bath,
  BedDouble,
  Blinds,
  Box,
  ChefHat,
  DoorClosed,
  DoorOpen,
  Droplets,
  Cylinder,
  Flame,
  Flower2,
  Grid2x2,
  Image,
  Lamp,
  LampDesk,
  Library,
  Monitor,
  RectangleHorizontal,
  Refrigerator,
  ScanFace,
  ShoppingBasket,
  ShowerHead,
  Sofa,
  Sprout,
  Table,
  Table2,
  Toilet,
  Tv,
  Utensils,
  WashingMachine,
  Waves,
  type LucideIcon,
  type LucideProps,
} from 'lucide-react';
import { createElement } from 'react';

const ICONS: Record<string, LucideIcon> = {
  sofa: Sofa,
  'bed-double': BedDouble,
  table: Table,
  armchair: Armchair,
  lamp: Lamp,
  library: Library,
  'rectangle-horizontal': RectangleHorizontal,
  sprout: Sprout,
  monitor: Monitor,
  archive: Archive,
  toilet: Toilet,
  droplets: Droplets,
  bath: Bath,
  'shower-head': ShowerHead,
  'scan-face': ScanFace,
  refrigerator: Refrigerator,
  flame: Flame,
  'chef-hat': ChefHat,
  'lamp-desk': LampDesk,
  'door-closed': DoorClosed,
  tv: Tv,
  door: DoorOpen,
  window: Grid2x2,
  cylinder: Cylinder,
  'table-2': Table2,
  utensils: Utensils,
  image: Image,
  blinds: Blinds,
  'flower-2': Flower2,
  'shopping-basket': ShoppingBasket,
  waves: Waves,
  'washing-machine': WashingMachine,
};

export const categoryIcon = (name: string | undefined): LucideIcon => (name && ICONS[name]) || Box;

export function CategoryIcon({ name, ...props }: { name: string | undefined } & LucideProps) {
  return createElement(categoryIcon(name), props);
}
